"""Every generated ``*_dace.py`` parses through the DaCe python frontend -- or is on the list.

The ``*_dace.py`` files are AUTOGENERATED by ``numpyto_c.dace_emit`` from the numpy reference, so a
construct the frontend refuses is not something a kernel author routes around: it lands straight in
the generator's output, and the kernel silently has no DaCe column. Nothing measured that until a
sweep did, and the answer was 190 of 576.

So this is a RATCHET on the refusals, not a pass/fail on the corpus. :data:`REFUSED` is the set
that is known not to parse; a kernel that starts refusing is a regression the gate fails on, and a
kernel that starts parsing must be REMOVED from the list -- an entry that no longer refuses is the
same silent drift a hand-written list always accumulates.

Parse only (``to_sdfg(simplify=False)``): no C++ compiler runs, so the whole corpus is affordable.
Each kernel is parsed in its own subprocess because a frontend that hangs (``cloudsc``) or dies
would otherwise take the session with it, and because DaCe's parse state is process-global.
"""
import json
import pathlib
import subprocess
import sys
from typing import Dict, List, Set

import pytest

REPO = pathlib.Path(__file__).resolve().parents[1]
BENCHMARKS = REPO / "hpcagent_bench" / "benchmarks"

#: Seconds one kernel's PARSE may take before it counts as a hang. Generous next to the ~2 s a
#: kernel actually takes: the budget is here to bound a wedged frontend, not to time anything.
PARSE_TIMEOUT_S = 180.0

#: Kernels whose generated DaCe program the frontend does not accept today, with the cause. Shrink
#: this list by fixing the GENERATOR (a desugar in ``dace_emit``) or by fixing DaCe -- never by
#: hand-editing a ``*_dace.py``, which is regenerated from the numpy reference on the next miss.
#:
#: The causes, measured 2026-08-06 over the whole corpus:
#:   broadcast     -- a padded conv/pool workspace is allocated with minted shape symbols, so a
#:                    write that is shape-equal by construction no longer proves it (64)
#:   matmul        -- ``numpy.matmul`` has no SDFG implementation registered (17)
#:   keyerror      -- a DaCe-internal ``KeyError`` naming a symbol: a crash, not a refusal (10)
#:   symbol_data   -- a scalar used BOTH as data and as a shape symbol (7)
#:   reassign      -- a second assignment to an array name the frontend treats as single-assignment (7)
#:   where_scalars -- ``np.where(cond, scalar, scalar)`` (6)
#:   undefined     -- a name the frontend cannot resolve in the emitted scope (7)
#:   keepdims      -- ``keepdims=`` on a reduction the frontend's replacement does not take (4)
#:   callback      -- an untyped callback return value (4)
#:   misc          -- one-off refusals: negative strides, a symbolic ``np.arange`` stop, a
#:                    ListComp, ``np.ix_``, a memlet dimensionality, a ``str`` where a node
#:                    belonged (10)
#:   hang          -- the frontend does not finish parsing at all (1)
REFUSED: Dict[str, str] = {}


def generated_programs() -> List[pathlib.Path]:
    """Every kernel's canonical DaCe program, GENERATING any that a fresh checkout lacks.

    ``*_dace.py`` is gitignored -- emitted from the numpy reference on demand -- so a glob alone
    measures whatever a previous run happened to leave behind, and on a CI runner that is nothing.
    ``.cache/`` copies are skipped: they are per-run duplicates whose dotted path is not importable.
    """
    from hpcagent_bench import autogen, paths
    from hpcagent_bench.spec import KERNELS, BenchSpec
    out: List[pathlib.Path] = []
    for key in sorted(KERNELS):
        spec = BenchSpec.load(key)
        autogen.ensure(key, ["dace"])
        canonical = paths.BENCHMARKS / spec.relative_path / f"{spec.module_name}_dace.py"
        if canonical.exists():
            out.append(canonical)
    return out


def parse_one(path: pathlib.Path) -> dict:
    """Parse ONE program in a fresh interpreter; ``{"verdict": "ok"|"fail"|"timeout"|"crash", ...}``.

    A subprocess per kernel because the two interesting failures -- a wedged parse and a hard crash
    -- are exactly the ones an in-process loop cannot survive to report.
    """
    argv = [sys.executable, "-m", "tests.dace_parse_probe", str(path)]
    try:
        proc = subprocess.run(argv, capture_output=True, text=True, cwd=str(REPO), timeout=PARSE_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        return {"verdict": "timeout", "error": f"the frontend did not finish parsing in {PARSE_TIMEOUT_S:.0f}s"}
    for line in reversed(proc.stdout.splitlines()):
        if line.startswith("{"):
            return json.loads(line)
    return {"verdict": "crash", "error": (proc.stderr or proc.stdout)[-400:]}


def kernel_of(path: pathlib.Path) -> str:
    """The kernel directory's name -- what :data:`REFUSED` is keyed on."""
    return path.parent.name


@pytest.mark.dace_frontend
def test_the_refusal_list_names_kernels_that_exist() -> None:
    """A stale entry would silently excuse a kernel that no longer exists, and hide a real
    regression behind a name nothing generates any more."""
    generated = {kernel_of(p) for p in generated_programs()}
    unknown = sorted(set(REFUSED) - generated)
    assert not unknown, (f"REFUSED names kernels with no generated DaCe program: {unknown}. "
                         "Remove them -- an entry that matches nothing excuses nothing.")


@pytest.mark.dace_frontend
def test_every_generated_dace_program_parses_or_is_a_known_refusal() -> None:
    """The ratchet. A NEW refusal fails; a refusal that started parsing fails too, so the list can
    only shrink, and it shrinks by fixing the generator."""
    programs = generated_programs()
    assert programs, "no generated DaCe programs found -- the glob or the corpus moved"
    regressions: List[str] = []
    fixed: Set[str] = set()
    for path in programs:
        kernel = kernel_of(path)
        verdict = parse_one(path)
        if verdict["verdict"] == "ok":
            if kernel in REFUSED:
                fixed.add(kernel)
        elif kernel not in REFUSED:
            regressions.append(f"{kernel}: {verdict['verdict']}: {verdict.get('error', '')[:200]}")
    assert not regressions, ("the DaCe frontend refuses generated programs that used to parse:\n  " +
                             "\n  ".join(sorted(regressions)))
    assert not fixed, (f"these parse now and must come OFF the REFUSED list: {sorted(fixed)}. "
                       "A list that keeps a fixed entry stops measuring the next regression.")
